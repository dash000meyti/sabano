import type { Metadata } from 'next';
import { locales, localeMeta, localizedPath, type Locale } from '@sabano/i18n';
import { absoluteUrl, pageUrl } from './site';

type Input = {
  locale: Locale;
  /** Locale-less path, e.g. '/about' */
  path: string;
  title: string;
  description: string;
  /** Absolute or root-relative image; defaults to the page OG image */
  image?: string;
  imageAlt?: string;
  type?: 'website' | 'article';
  /** Locales this page exists in (defaults to all) */
  availableLocales?: readonly Locale[];
  noindex?: boolean;
  publishedTime?: Date;
  modifiedTime?: Date;
  /** Use the title as-is instead of appending the brand */
  absoluteTitle?: boolean;
};

const brand: Record<Locale, string> = { fa: 'صبانو', en: 'Sabano', zh: 'Sabano', ru: 'Sabano', es: 'Sabano' };

/** Default OG image per page key, generated by scripts/generate-og.mjs. */
export function ogImageFor(locale: Locale, key: string) {
  return `/og/${locale}/${key}.jpg`;
}

export function buildMetadata(input: Input): Metadata {
  const { locale, path } = input;
  const available = input.availableLocales ?? locales;
  const languages: Record<string, string> = {};
  for (const l of available) languages[localeMeta[l].hreflang] = pageUrl(l, path);
  if (available.includes('fa')) languages['x-default'] = pageUrl('fa', path);

  const title = input.absoluteTitle || input.title.includes(brand[locale])
    ? input.title
    : `${input.title} | ${brand[locale]}`;
  const image = input.image ? absoluteUrl(input.image) : undefined;

  return {
    title: { absolute: title },
    description: input.description,
    alternates: { canonical: pageUrl(locale, path), languages },
    robots: input.noindex ? { index: false, follow: true } : { index: true, follow: true, 'max-image-preview': 'large', 'max-snippet': -1 },
    openGraph: {
      type: input.type ?? 'website',
      url: pageUrl(locale, path),
      siteName: brand[locale],
      locale: localeMeta[locale].og,
      alternateLocale: available.filter((l) => l !== locale).map((l) => localeMeta[l].og),
      title,
      description: input.description,
      ...(image ? { images: [{ url: image, width: 1200, height: 630, alt: input.imageAlt ?? input.title }] } : {}),
      ...(input.publishedTime ? { publishedTime: input.publishedTime.toISOString() } : {}),
      ...(input.modifiedTime ? { modifiedTime: input.modifiedTime.toISOString() } : {}),
    },
    twitter: {
      card: 'summary_large_image',
      title,
      description: input.description,
      ...(image ? { images: [image] } : {}),
    },
  };
}

export { localizedPath };
